import { supabase } from "@/lib/supabase/client";

export type DailyChallenge = {
  date: string;
  startTitle: string;
  destinationTitle: string;
};

export function todayUtc(): string {
  return new Date().toISOString().slice(0, 10);
}

function pickTwoDistinct(titles: string[], avoid: Set<string>): [string, string] | null {
  const unique = [...new Set(titles)];
  const fresh = unique.filter((t) => !avoid.has(t));
  const pool = fresh.length >= 2 ? fresh : unique;
  if (pool.length < 2) return null;
  const shuffled = pool.sort(() => Math.random() - 0.5);
  return [shuffled[0], shuffled[1]];
}

// Lazily generated by whoever visits first each day — no cron needed for
// MVP, and this doubles as a safety net if a scheduled job ever misses.
export async function getOrCreateTodayChallenge(): Promise<DailyChallenge | null> {
  const date = todayUtc();

  const { data: existing } = await supabase
    .from("daily_challenges")
    .select("challenge_date, start_title, destination_title")
    .eq("challenge_date", date)
    .maybeSingle();

  if (existing) {
    return { date: existing.challenge_date, startTitle: existing.start_title, destinationTitle: existing.destination_title };
  }

  const { data: pool } = await supabase.from("article_metadata").select("title").eq("difficulty_tier", "medium").limit(50);

  const { data: recent } = await supabase
    .from("daily_challenges")
    .select("start_title, destination_title")
    .order("challenge_date", { ascending: false })
    .limit(14);
  const avoid = new Set((recent ?? []).flatMap((r) => [r.start_title, r.destination_title]));

  const pair = pickTwoDistinct((pool ?? []).map((r) => r.title), avoid);
  if (!pair) return null;
  const [startTitle, destinationTitle] = pair;

  // on_conflict do-nothing handles two concurrent first-visitors of the
  // day racing to create the row — whichever insert wins, re-select after.
  await supabase
    .from("daily_challenges")
    .upsert(
      { challenge_date: date, start_title: startTitle, destination_title: destinationTitle, difficulty_tier: "medium" },
      { onConflict: "challenge_date", ignoreDuplicates: true },
    );

  const { data: final } = await supabase
    .from("daily_challenges")
    .select("challenge_date, start_title, destination_title")
    .eq("challenge_date", date)
    .single();

  return {
    date: final?.challenge_date ?? date,
    startTitle: final?.start_title ?? startTitle,
    destinationTitle: final?.destination_title ?? destinationTitle,
  };
}
